local function layoutDefaults(base, settings)
    local layout = { frames = GUF.Copy(base.frames), threat = GUF.Copy(settings.threat),
        hideBlizzard = GUF.Copy(settings.hideBlizzard) }
    for _, unit in ipairs(GUF.order) do layout.frames[unit] = GUF.Copy(settings.frames[unit]) end
    return layout
end

